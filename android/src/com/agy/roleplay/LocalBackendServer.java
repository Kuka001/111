    private JSONArray buildSafetySettingsArray(String threshold, boolean includeExtendedCategories) throws Exception {
        String normThreshold = normalizeSafetyThreshold(threshold);
        String[] categories = includeExtendedCategories
            ? new String[]{
                "HARM_CATEGORY_HATE_SPEECH",
                "HARM_CATEGORY_DANGEROUS_CONTENT",
                "HARM_CATEGORY_HARASSMENT",
                "HARM_CATEGORY_SEXUALLY_EXPLICIT",
                "HARM_CATEGORY_CIVIC_INTEGRITY"
            }
            : new String[]{
                "HARM_CATEGORY_HATE_SPEECH",
                "HARM_CATEGORY_DANGEROUS_CONTENT",
                "HARM_CATEGORY_HARASSMENT",
                "HARM_CATEGORY_SEXUALLY_EXPLICIT"
            };
        JSONArray arr = new JSONArray();
        for (String cat : categories) {
            JSONObject item = new JSONObject();
            item.put("category", cat);
            item.put("threshold", normThreshold);
            arr.put(item);
        }
        return arr;
    }

    private String summarizeSafetyRatings(JSONArray ratings) {
        if (ratings == null || ratings.length() == 0) return "";
        StringBuilder sb = new StringBuilder();
        for (int i = 0; i < ratings.length(); i++) {
            JSONObject r = ratings.optJSONObject(i);
            if (r == null) continue;
            String cat = r.optString("category", "").replace("HARM_CATEGORY_", "");
            String prob = r.optString("probability", "");
            String sev = r.optString("severity", "").replace("HARM_SEVERITY_", "");
            boolean blocked = r.optBoolean("blocked", false);
            if (cat.isEmpty()) continue;
            if (sb.length() > 0) sb.append(", ");
            sb.append(cat).append("=").append(prob.isEmpty() ? "?" : prob);
            if (!sev.isEmpty() && !"UNSPECIFIED".equals(sev)) {
                sb.append("/sev:").append(sev);
            }
            if (blocked) sb.append("(BLOCKED)");
        }
        return sb.toString();
    }

    private String readHttpBody(HttpURLConnection conn) {
        try {
            InputStream is = (conn.getResponseCode() >= 200 && conn.getResponseCode() < 400)
                ? conn.getInputStream()
                : conn.getErrorStream();
            if (is == null) return "";
            BufferedReader br = new BufferedReader(new InputStreamReader(is, StandardCharsets.UTF_8));
            StringBuilder sb = new StringBuilder();
            String line;
            while ((line = br.readLine()) != null) {
                sb.append(line).append("\n");
            }
            br.close();
            return sb.toString().trim();
        } catch (Exception e) {
            return "";
        }
    }

