    /** Adds a column to an existing table if it is not already present. */
    private void addColumnIfMissing(String table, String column, String typeDecl) {
        if (db == null) return;
        try {
            boolean present = false;
            Cursor c = db.rawQuery("PRAGMA table_info(" + table + ")", null);
            try {
                int nameIdx = c.getColumnIndex("name");
                while (c.moveToNext()) {
                    if (column.equalsIgnoreCase(c.getString(nameIdx))) {
                        present = true;
                        break;
                    }
                }
            } finally {
                c.close();
            }
            if (!present) {
                db.execSQL("ALTER TABLE " + table + " ADD COLUMN " + column + " " + typeDecl);
            }
        } catch (Exception ignored) {
        }
    }

    private void setDefaultSetting(String key, String value) {
        if (db == null) return;
        try {
            Cursor c = db.rawQuery("SELECT value FROM settings WHERE key = ?", new String[]{key});
            boolean exists = c.moveToFirst();
            c.close();
            if (!exists) {
                ContentValues cv = new ContentValues();
                cv.put("key", key);
                cv.put("value", value);
                db.insert("settings", null, cv);
            }
        } catch (Exception ignored) {
        }
    }

