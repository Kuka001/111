    // -------------------------------------------------------------------------
    // SECRET SETTINGS AT REST
    // -------------------------------------------------------------------------
    // OAuth access/refresh tokens grant access to the user's Google account.
    // They are encrypted with an AES-256-GCM key held in the hardware-backed
    // Android Keystore, so the raw SQLite file alone (ADB backup, stolen device
    // image, rooted file read) does not yield usable credentials.
    private static final String KEYSTORE_PROVIDER = "AndroidKeyStore";
    private static final String SECRET_KEY_ALIAS = "agy_settings_secret_key_v1";
    private static final String ENC_PREFIX = "enc:v1:";
    private static final int GCM_IV_LENGTH = 12;
    private static final int GCM_TAG_BITS = 128;

    private static final java.util.Set<String> SECRET_SETTING_KEYS =
        new java.util.HashSet<>(Arrays.asList(
            "agy_access_token",
            "agy_refresh_token",
            "google_auth_token"
        ));

    private javax.crypto.SecretKey getOrCreateSecretKey() throws Exception {
        java.security.KeyStore ks = java.security.KeyStore.getInstance(KEYSTORE_PROVIDER);
        ks.load(null);
        java.security.KeyStore.Entry entry = ks.getEntry(SECRET_KEY_ALIAS, null);
        if (entry instanceof java.security.KeyStore.SecretKeyEntry) {
            return ((java.security.KeyStore.SecretKeyEntry) entry).getSecretKey();
        }
        javax.crypto.KeyGenerator kg =
            javax.crypto.KeyGenerator.getInstance(android.security.keystore.KeyProperties.KEY_ALGORITHM_AES, KEYSTORE_PROVIDER);
        kg.init(new android.security.keystore.KeyGenParameterSpec.Builder(
                SECRET_KEY_ALIAS,
                android.security.keystore.KeyProperties.PURPOSE_ENCRYPT
                    | android.security.keystore.KeyProperties.PURPOSE_DECRYPT)
            .setBlockModes(android.security.keystore.KeyProperties.BLOCK_MODE_GCM)
            .setEncryptionPaddings(android.security.keystore.KeyProperties.ENCRYPTION_PADDING_NONE)
            .setKeySize(256)
            .build());
        return kg.generateKey();
    }

    /** Encrypts a secret value; returns the plain value if the Keystore is unavailable. */
    private String encryptSecret(String plain) {
        if (plain == null || plain.isEmpty()) return "";
        try {
            javax.crypto.Cipher cipher = javax.crypto.Cipher.getInstance("AES/GCM/NoPadding");
            cipher.init(javax.crypto.Cipher.ENCRYPT_MODE, getOrCreateSecretKey());
            byte[] iv = cipher.getIV();
            byte[] ct = cipher.doFinal(plain.getBytes(StandardCharsets.UTF_8));
            byte[] combined = new byte[iv.length + ct.length];
            System.arraycopy(iv, 0, combined, 0, iv.length);
            System.arraycopy(ct, 0, combined, iv.length, ct.length);
            return ENC_PREFIX + Base64.encodeToString(combined, Base64.NO_WRAP);
        } catch (Exception e) {
            // Never lose the user's session because crypto is unavailable.
            return plain;
        }
    }

    /** Decrypts a stored secret. Plaintext values (pre-upgrade rows) pass through. */
    private String decryptSecret(String stored) {
        if (stored == null || stored.isEmpty()) return "";
        if (!stored.startsWith(ENC_PREFIX)) return stored;
        try {
            byte[] combined = Base64.decode(stored.substring(ENC_PREFIX.length()), Base64.NO_WRAP);
            if (combined.length <= GCM_IV_LENGTH) return "";
            byte[] iv = Arrays.copyOfRange(combined, 0, GCM_IV_LENGTH);
            byte[] ct = Arrays.copyOfRange(combined, GCM_IV_LENGTH, combined.length);
            javax.crypto.Cipher cipher = javax.crypto.Cipher.getInstance("AES/GCM/NoPadding");
            cipher.init(javax.crypto.Cipher.DECRYPT_MODE, getOrCreateSecretKey(),
                new javax.crypto.spec.GCMParameterSpec(GCM_TAG_BITS, iv));
            return new String(cipher.doFinal(ct), StandardCharsets.UTF_8);
        } catch (Exception e) {
            // Key rotated/invalidated: treat as "no token" and force re-auth.
            return "";
        }
    }

    /** Re-encrypts any token rows left in plaintext by an older build. */
    private void migratePlaintextSecrets() {
        for (String key : SECRET_SETTING_KEYS) {
            try {
                if (db == null) return;
                Cursor c = db.rawQuery("SELECT value FROM settings WHERE key = ?", new String[]{key});
                String raw = null;
                if (c.moveToFirst()) raw = c.getString(0);
                c.close();
                if (raw != null && !raw.isEmpty() && !raw.startsWith(ENC_PREFIX)) {
                    ContentValues cv = new ContentValues();
                    cv.put("key", key);
                    cv.put("value", encryptSecret(raw));
                    db.insertWithOnConflict("settings", null, cv, SQLiteDatabase.CONFLICT_REPLACE);
                }
            } catch (Exception ignored) {
            }
        }
    }

    /**
     * Decrypted secrets, so a status call does not pay an Android Keystore round
     * trip per token (tens of milliseconds each). Filled on first read, kept in
     * step by setSetting, which is the only writer.
     */
    private final Map<String, String> secretCache = new ConcurrentHashMap<>();

    private String getSetting(String key, String fallback) {
        if (db == null) return fallback;
        boolean secret = SECRET_SETTING_KEYS.contains(key);
        if (secret) {
            String cached = secretCache.get(key);
            if (cached != null) return cached;
        }
        try {
            Cursor c = db.rawQuery("SELECT value FROM settings WHERE key = ?", new String[]{key});
            String val = null;
            if (c.moveToFirst()) {
                val = c.getString(0);
            }
            c.close();
            if (val == null) return fallback;
            if (secret) {
                String plain = decryptSecret(val);
                secretCache.put(key, plain);
                return plain;
            }
            return val;
        } catch (Exception e) {
            return fallback;
        }
    }

    private void setSetting(String key, String value) {
        if (db == null) return;
        try {
            String toStore = value != null ? value : "";
            if (SECRET_SETTING_KEYS.contains(key) && !toStore.isEmpty()) {
                toStore = encryptSecret(toStore);
            }
            ContentValues cv = new ContentValues();
            cv.put("key", key);
            cv.put("value", toStore);
            db.insertWithOnConflict("settings", null, cv, SQLiteDatabase.CONFLICT_REPLACE);
            if (SECRET_SETTING_KEYS.contains(key)) secretCache.put(key, value != null ? value : "");
        } catch (Exception ignored) {
            secretCache.remove(key);
        }
    }

    /**
     * Reconciles card rows with the card files: rows whose file is gone are
     * removed, files without a row get one. Runs at start-up and after a backup
     * restore; everything else changes cards through the API, which updates
     * both sides at once.
     */
    private synchronized void syncWorkspaceFilesWithDb() {
        pruneMissingCardRows("characters");
        pruneMissingCardRows("personas");
        for (File f : cardFiles("characters")) {
            String relPath = "characters/" + f.getName();
            if (rowExists("characters", relPath)) continue;
            String content = readTextFile(f);
            String name = parseHeaderName(content, stripExtension(f.getName()));
            ContentValues cv = new ContentValues();
            cv.put("name", name);
            cv.put("file_path", relPath);
            cv.put("avatar_url", "");
            cv.put("first_message", parseFirstMessage(content));
            cv.put("description_preview", parsePreview(content));
            db.insert("characters", null, cv);
        }
        for (File f : cardFiles("personas")) {
            String relPath = "personas/" + f.getName();
            if (rowExists("personas", relPath)) continue;
            String content = readTextFile(f);
            ContentValues cv = new ContentValues();
            cv.put("name", parseHeaderName(content, stripExtension(f.getName())));
            cv.put("file_path", relPath);
            cv.put("avatar_url", "");
            cv.put("description_preview", parsePreview(content));
            cv.put("is_default", 1);
            db.insert("personas", null, cv);
        }
    }

    private void pruneMissingCardRows(String table) {
        List<String> gone = new ArrayList<>();
        Cursor c = db.rawQuery("SELECT id, file_path FROM " + table, null);
        try {
            while (c.moveToNext()) {
                String fp = c.getString(1);
                if (fp == null || fp.isEmpty() || !new File(workspaceDir, fp).isFile()) gone.add(String.valueOf(c.getInt(0)));
            }
        } finally {
            c.close();
        }
        for (String id : gone) db.delete(table, "id = ?", new String[]{id});
    }

    /** Card files (.md / .txt) of a workspace folder, sorted by name. */
    private File[] cardFiles(String dir) {
        File[] files = new File(workspaceDir, dir).listFiles();
        if (files == null) return new File[0];
        List<File> out = new ArrayList<>();
        for (File f : files) {
            String n = f.getName();
            if (f.isFile() && (n.endsWith(".md") || n.endsWith(".txt"))) out.add(f);
        }
        Collections.sort(out, new Comparator<File>() {
            @Override
            public int compare(File a, File b) {
                return a.getName().compareToIgnoreCase(b.getName());
            }
        });
        return out.toArray(new File[0]);
    }

    private boolean rowExists(String table, String filePath) {
        Cursor c = db.rawQuery("SELECT 1 FROM " + table + " WHERE file_path = ?", new String[]{filePath});
        try {
            return c.moveToFirst();
        } finally {
            c.close();
        }
    }

    private static String stripExtension(String fileName) {
        return fileName.replaceFirst("\\.[^.]+$", "");
    }

    private String parseHeaderName(String content, String fallback) {
        Matcher m = Pattern.compile("^#\\s*(?:Имя:|Персона:|Персонаж:)?\\s*(.+)$", Pattern.MULTILINE | Pattern.CASE_INSENSITIVE).matcher(content);
        if (m.find()) {
            return m.group(1).trim();
        }
        return fallback;
    }

    private String parseFirstMessage(String content) {
        Matcher m = Pattern.compile("###\\s*(?:Начальное сообщение|Приветствие|First Message)\\s*\\r?\\n([\\s\\S]+?)(?:\\r?\\n###|$)", Pattern.CASE_INSENSITIVE).matcher(content);
        if (m.find()) {
            return m.group(1).trim();
        }
        return "";
    }

    private String parsePreview(String content) {
        String cleaned = content
            .replaceAll("(?m)^#+.*$", "")
            .replaceAll("\\s+", " ")
            .trim();
        if (cleaned.length() > 160) {
            return cleaned.substring(0, 160);
        }
        return cleaned;
    }

