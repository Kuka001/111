    // =========================================================================
    // FULL BACKUP & RESTORE
    // =========================================================================
    // The APK signing key lives only on the developer's machine: if it is lost,
    // a future APK cannot be installed over this one and the user must uninstall,
    // which wipes every chat. A portable, self-contained backup is the only way
    // out of that, so it covers both the SQLite data and the workspace files.
    private static final int BACKUP_FORMAT_VERSION = 1;

    /** Tables included in a backup. `settings` is handled separately (secrets are stripped). */
    private static final String[] BACKUP_TABLES =
        new String[]{"characters", "personas", "chats", "messages"};

    /** Dumps a table generically, so added columns are carried along automatically. */
    private JSONArray dumpTable(String table) throws Exception {
        JSONArray rows = new JSONArray();
        Cursor c = db.rawQuery("SELECT * FROM " + table, null);
        try {
            String[] cols = c.getColumnNames();
            while (c.moveToNext()) {
                JSONObject row = new JSONObject();
                for (int i = 0; i < cols.length; i++) {
                    if (c.isNull(i)) {
                        row.put(cols[i], JSONObject.NULL);
                    } else {
                        row.put(cols[i], c.getString(i));
                    }
                }
                rows.put(row);
            }
        } finally {
            c.close();
        }
        return rows;
    }

    /** Recursively collects workspace files as UTF-8 text keyed by relative path. */
    private void collectWorkspaceFiles(File dir, String prefix, JSONObject out) throws Exception {
        File[] children = dir.listFiles();
        if (children == null) return;
        for (File f : children) {
            String rel = prefix.isEmpty() ? f.getName() : prefix + "/" + f.getName();
            if (f.isDirectory()) {
                collectWorkspaceFiles(f, rel, out);
            } else if (f.isFile() && f.length() <= 2_000_000L) {
                try {
                    out.put(rel, readTextFile(f));
                } catch (Exception ignored) {
                    // Skip unreadable/binary files rather than failing the whole backup.
                }
            }
        }
    }

    private JSONObject handleBackupExport() throws Exception {
        JSONObject res = new JSONObject();
        res.put("backupFormat", BACKUP_FORMAT_VERSION);
        res.put("appVersion", readBundledVersionManifest().optString("version", ""));
        res.put("exportedAt", new java.text.SimpleDateFormat("yyyy-MM-dd'T'HH:mm:ss", Locale.US).format(new java.util.Date()));

        JSONObject tables = new JSONObject();
        for (String t : BACKUP_TABLES) {
            tables.put(t, dumpTable(t));
        }
        res.put("tables", tables);

        // Non-secret settings only: OAuth tokens are deliberately excluded so a
        // backup file can be stored or shared without leaking Google credentials.
        JSONObject settings = new JSONObject();
        Cursor c = db.rawQuery("SELECT key, value FROM settings", null);
        try {
            while (c.moveToNext()) {
                String key = c.getString(0);
                if (SECRET_SETTING_KEYS.contains(key)) continue;
                settings.put(key, c.getString(1));
            }
        } finally {
            c.close();
        }
        res.put("settings", settings);

        JSONObject files = new JSONObject();
        collectWorkspaceFiles(workspaceDir, "", files);
        res.put("workspaceFiles", files);

        res.put("counts", new JSONObject()
            .put("characters", tables.getJSONArray("characters").length())
            .put("personas", tables.getJSONArray("personas").length())
            .put("chats", tables.getJSONArray("chats").length())
            .put("messages", tables.getJSONArray("messages").length())
            .put("workspaceFiles", files.length()));
        return res;
    }

    private JSONObject handleBackupImport(JSONObject body) throws Exception {
        JSONObject backup = body.optJSONObject("backup");
        if (backup == null) {
            // Also accept the backup pasted as a raw JSON string.
            String raw = body.optString("backupJson", "").trim();
            if (raw.isEmpty()) {
                return errorJson(400, "Нет данных резервной копии (ожидается поле backup или backupJson)");
            }
            try {
                backup = new JSONObject(raw);
            } catch (Exception e) {
                return errorJson(400, "Файл резервной копии повреждён: не удалось разобрать JSON");
            }
        }

        int fmt = backup.optInt("backupFormat", 0);
        if (fmt <= 0 || fmt > BACKUP_FORMAT_VERSION) {
            return errorJson(400, "Неподдерживаемый формат резервной копии: " + fmt);
        }
        JSONObject tables = backup.optJSONObject("tables");
        if (tables == null) {
            return errorJson(400, "Резервная копия не содержит раздел tables");
        }

        // Destructive replace, wrapped in a transaction so a failure cannot leave
        // the database half-wiped.
        int restoredRows = 0;
        db.beginTransaction();
        try {
            for (int i = BACKUP_TABLES.length - 1; i >= 0; i--) {
                db.execSQL("DELETE FROM " + BACKUP_TABLES[i]);
            }
            for (String t : BACKUP_TABLES) {
                JSONArray rows = tables.optJSONArray(t);
                if (rows == null) continue;
                for (int i = 0; i < rows.length(); i++) {
                    JSONObject row = rows.optJSONObject(i);
                    if (row == null) continue;
                    ContentValues cv = new ContentValues();
                    java.util.Iterator<String> keys = row.keys();
                    while (keys.hasNext()) {
                        String k = keys.next();
                        if (row.isNull(k)) {
                            cv.putNull(k);
                        } else {
                            cv.put(k, row.optString(k));
                        }
                    }
                    if (cv.size() > 0) {
                        db.insertWithOnConflict(t, null, cv, SQLiteDatabase.CONFLICT_REPLACE);
                        restoredRows++;
                    }
                }
            }

            JSONObject settings = backup.optJSONObject("settings");
            if (settings != null) {
                java.util.Iterator<String> keys = settings.keys();
                while (keys.hasNext()) {
                    String k = keys.next();
                    // Never restore secrets or OTA trust state from a backup file.
                    if (SECRET_SETTING_KEYS.contains(k)) continue;
                    if ("ota_active".equals(k) || "installed_build".equals(k)
                        || "installed_version".equals(k) || "installed_commit".equals(k)) {
                        continue;
                    }
                    setSetting(k, settings.optString(k));
                }
            }
            db.setTransactionSuccessful();
        } finally {
            db.endTransaction();
        }

        // Workspace files are restored outside the DB transaction.
        int restoredFiles = 0;
        JSONObject files = backup.optJSONObject("workspaceFiles");
        if (files != null) {
            java.util.Iterator<String> keys = files.keys();
            File wsRoot = workspaceDir.getCanonicalFile();
            while (keys.hasNext()) {
                String rel = keys.next();
                if (rel.contains("..")) continue;
                try {
                    File target = new File(workspaceDir, rel);
                    // Path-traversal guard: never write outside the workspace.
                    if (!target.getCanonicalPath().startsWith(wsRoot.getPath())) continue;
                    File parent = target.getParentFile();
                    if (parent != null && !parent.exists()) parent.mkdirs();
                    writeTextFile(target, files.optString(rel));
                    restoredFiles++;
                } catch (Exception ignored) {
                }
            }
        }

        JSONObject res = new JSONObject();
        res.put("ok", true);
        res.put("restoredRows", restoredRows);
        res.put("restoredFiles", restoredFiles);
        res.put("message", "Восстановлено записей: " + restoredRows + ", файлов: " + restoredFiles
            + ". Авторизация Google не восстанавливается из резервной копии — войдите заново при необходимости.");
        return res;
    }

