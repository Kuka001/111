    /**
     * Starts `claude auth login --claudeai` (the non-interactive sign-in that
     * works without a terminal) and returns at once; the UI polls
     * /api/claude/status for the live output, the sign-in links and the result.
     *
     * Two links appear once Claude Code is ready: the manual one (printed on
     * stdout; the page then shows a code#state to paste back) and the automatic
     * one (handed to $BROWSER, captured by our shim; the browser then returns
     * the sign-in to the CLI's localhost listener, nothing to paste). Nothing is
     * opened automatically: the user picks a link in the app.
     */
    private JSONObject handleClaudeAuthStart() throws Exception {
        if (!claudeRuntime.isReady()) {
            return errorJson(409, "Сначала скачайте среду Claude Code.");
        }

        // Tear down any half-finished previous attempt, and runs left hanging.
        stopPendingClaudeAuth();
        claudeRuntime.killStray(liveSandboxRuns());
        claudeLoginError = "";
        claudeLoginManualUrl = "";
        synchronized (claudeLoginOutput) { claudeLoginOutput.setLength(0); }
        refreshGuestDns();
        claudeRuntime.ensureBrowserShim();
        claudeRuntime.browserUrlFile().delete();
        claudeRuntime.tmpFile(CLAUDE_LOGIN_DEBUG_LOG).delete();

        // --debug-to-stderr: the debug log arrives line by line as it is written
        // (a --debug-file is flushed late, and stays empty if the CLI hangs).
        // Global options go before the subcommand: the CLI parses positionally.
        List<String> args = new ArrayList<>();
        args.add("--debug-to-stderr");
        args.add("auth");
        args.add("login");
        args.add("--claudeai");
        ProcessBuilder pb = claudeRuntime.newClaudeProcess(args, claudeRuntime.defaultOptions());
        pb.environment().put("BROWSER", claudeRuntime.browserShimPath());
        final Process proc;
        try {
            proc = pb.start();
        } catch (Exception e) {
            claudeLoginError = "Не удалось запустить среду: " + e.getMessage();
            return errorJson(500, claudeLoginError);
        }
        pendingClaudeAuthProcess = proc;
        claudeLoginStartedAt = System.currentTimeMillis();
        claudeLoginBaseStamp = claudeRuntime.credentialsStamp();

        startLoginReader(proc.getInputStream(), true);
        startLoginReader(proc.getErrorStream(), false);

        // Watch the process: success stores credentials; anything else is reported.
        Thread watcher = new Thread(new Runnable() {
            @Override
            public void run() {
                try {
                    int code = proc.waitFor();
                    // Stopped on purpose (cancel, a new attempt, the hang watchdog
                    // below): nothing to report, or the report is already there.
                    boolean current = pendingClaudeAuthProcess == proc;
                    if (current) pendingClaudeAuthProcess = null;
                    if (current && !newCredentialsStored() && claudeLoginError.isEmpty()) {
                        String out = loginOutputTail();
                        claudeLoginError = "Вход не завершён (" + describeExit(code) + ")"
                            + (out.isEmpty() ? "." : ":\n" + out);
                    }
                } catch (InterruptedException ignored) {
                }
            }
        });
        watcher.setDaemon(true);
        watcher.start();

        // No link at all after the timeout: Claude Code hung while starting.
        // Record what every sandbox process is doing, then stop the attempt.
        Thread watchdog = new Thread(new Runnable() {
            @Override
            public void run() {
                long deadline = System.currentTimeMillis() + CLAUDE_LOGIN_START_TIMEOUT_MS;
                while (System.currentTimeMillis() < deadline) {
                    if (pendingClaudeAuthProcess != proc || !isAlive(proc)) return;
                    if (!claudeLoginManualUrl.isEmpty() || !readFirstUrl(claudeRuntime.browserUrlFile()).isEmpty()) return;
                    try { Thread.sleep(500); } catch (InterruptedException e) { return; }
                }
                if (pendingClaudeAuthProcess != proc || !isAlive(proc) || newCredentialsStored()) return;
                if (!claudeLoginManualUrl.isEmpty() || !readFirstUrl(claudeRuntime.browserUrlFile()).isEmpty()) return;
                String snapshot = sandboxSnapshot();
                String out = loginOutputTail();
                claudeLoginError = "Claude Code не ответил за " + (CLAUDE_LOGIN_START_TIMEOUT_MS / 1000)
                    + " с: завис при запуске, ещё до ссылки для входа. Нажмите «Проверить запуск» —"
                    + " проверка подберёт режим, в котором Claude Code запускается на этом телефоне.\n"
                    + (out.isEmpty() ? "\n(Claude Code ничего не вывел)" : "\n--- вывод ---\n" + out)
                    + "\n--- процессы ---\n" + snapshot;
                stopPendingClaudeAuth();
            }
        });
        watchdog.setDaemon(true);
        watchdog.start();

        JSONObject res = new JSONObject();
        res.put("ok", true);
        res.put("pending", true);
        return res;
    }

    private void startLoginReader(final InputStream stream, final boolean scanUrls) {
        Thread t = new Thread(new Runnable() {
            @Override
            public void run() {
                try {
                    BufferedReader br = new BufferedReader(new InputStreamReader(stream, StandardCharsets.UTF_8));
                    String l;
                    while ((l = br.readLine()) != null) {
                        String clean = stripAnsi(l);
                        synchronized (claudeLoginOutput) {
                            // Debug lines keep coming: keep the latest part.
                            claudeLoginOutput.append(clean).append("\n");
                            if (claudeLoginOutput.length() > 24000) claudeLoginOutput.delete(0, claudeLoginOutput.length() - 16000);
                        }
                        if (scanUrls && claudeLoginManualUrl.isEmpty()) {
                            String url = extractFirstUrl(clean);
                            if (url != null) claudeLoginManualUrl = url;
                        }
                    }
                } catch (Exception ignored) {
                }
            }
        });
        t.setDaemon(true);
        t.start();
    }

    /** Passes the active network's DNS servers to the sandbox resolv.conf. */
    private void refreshGuestDns() {
        List<String> servers = new ArrayList<>();
        try {
            android.net.ConnectivityManager cm =
                (android.net.ConnectivityManager) context.getSystemService(Context.CONNECTIVITY_SERVICE);
            if (cm != null && android.os.Build.VERSION.SDK_INT >= 23) {
                android.net.Network net = cm.getActiveNetwork();
                android.net.LinkProperties lp = net != null ? cm.getLinkProperties(net) : null;
                if (lp != null) {
                    for (InetAddress a : lp.getDnsServers()) {
                        String h = a.getHostAddress();
                        if (h != null) servers.add(h);
                    }
                }
            }
        } catch (Exception ignored) {
        }
        claudeRuntime.setDnsServers(servers);
    }

    private String fileTail(File f, int max) {
        if (f == null || !f.isFile()) return "";
        String text = stripAnsi(readTextFile(f)).trim();
        return text.length() > max ? "…" + text.substring(text.length() - max) : text;
    }

    private JSONObject handleClaudeAuthExchange(JSONObject body) throws Exception {
        String code = body.optString("code", "").trim();
        if (code.isEmpty()) return errorJson(400, "Вставьте код со страницы входа Claude");
        if (newCredentialsStored()) {
            JSONObject done = new JSONObject();
            done.put("ok", true);
            done.put("authenticated", true);
            return done;
        }

        Process proc = pendingClaudeAuthProcess;
        if (proc == null || !isAlive(proc)) {
            return errorJson(409, "Сессия входа не активна. Нажмите «Войти» заново.");
        }
        if (!code.contains("#")) {
            return errorJson(400, "Скопируйте код целиком — вместе с частью после «#».");
        }
        try {
            OutputStream stdin = proc.getOutputStream();
            stdin.write((code + "\n").getBytes(StandardCharsets.UTF_8));
            stdin.flush();
        } catch (Exception e) {
            return errorJson(500, "Не удалось передать код процессу: " + e.getMessage());
        }

        // Give the CLI time to exchange the code and persist credentials.
        long deadline = System.currentTimeMillis() + 45000L;
        while (System.currentTimeMillis() < deadline && isAlive(proc) && !newCredentialsStored()) {
            try { Thread.sleep(400); } catch (InterruptedException ignored) { break; }
        }

        boolean authed = newCredentialsStored();
        JSONObject res = new JSONObject();
        res.put("ok", authed);
        res.put("authenticated", authed);
        if (!authed) {
            String out = loginOutputTail();
            res.put("error", "Вход не завершился." + (out.isEmpty() ? " Проверьте код и повторите." : "\n" + out));
        }
        return res;
    }

    /**
     * «Проверить запуск»: (1) does Claude Code start at all (--version), (2) the
     * probe checks, one by one, the Bun runtime features it relies on, (3) a
     * full start (auth status, with the start-up trace). If the full start
     * fails, it is retried with Bun's safe flags and then with an empty
     * profile; the first set-up that works is kept for sign-in and replies.
     */
    private JSONObject handleClaudeSelfTest() throws Exception {
        if (!claudeRuntime.isReady()) {
            return errorJson(409, "Сначала скачайте среду Claude Code.");
        }
        synchronized (this) {
            if (claudeSelftestRunning) return errorJson(409, "Проверка уже идёт.");
            claudeSelftestRunning = true;
        }
        try {
            return runClaudeSelfTest();
        } finally {
            claudeSelftestRunning = false;
            claudeSelftestProgress = "";
        }
    }

    private JSONObject runClaudeSelfTest() throws Exception {
        int stray = claudeRuntime.killStray(liveSandboxRuns());
        refreshGuestDns();
        JSONArray stages = new JSONArray();
        StringBuilder report = new StringBuilder();
        report.append("AGY Claude Code self-test · engine build ").append(getEngineBuild())
            .append(" · Android ").append(android.os.Build.VERSION.RELEASE)
            .append(" (API ").append(android.os.Build.VERSION.SDK_INT).append(") · ")
            .append(android.os.Build.MANUFACTURER).append(' ').append(android.os.Build.MODEL)
            .append(" · ").append(android.os.Build.SUPPORTED_ABIS.length > 0 ? android.os.Build.SUPPORTED_ABIS[0] : "?")
            .append("\nruntime ").append(ClaudeRuntime.version())
            .append(" · режим до проверки: ").append(claudeRuntime.isSafeMode() ? "безопасный Bun" : "обычный")
            .append("\nresolv.conf: ").append(claudeRuntime.resolvConf().trim().replace("\n", "; ")).append("\n");
        if (stray > 0) report.append("остановлено зависших запусков с прошлых раз: ").append(stray).append("\n");
        final int headerEnd = report.length();

        // 1. Does the binary start at all?
        List<String> version = new ArrayList<>();
        version.add("--version");
        claudeSelftestProgress = "Claude Code · версия";
        JSONObject v = runStage("Claude Code · версия",
            claudeRuntime.newClaudeProcess(version, new ClaudeRuntime.RunOptions()), 30000L, 30000L, null, true);
        stages.put(v);
        appendStage(report, v);

        boolean ok = false;
        String summary;
        if (!v.optBoolean("ok")) {
            summary = v.optBoolean("finished")
                ? "Claude Code не запускается на этом телефоне (" + v.optString("exit") + "). Скопируйте отчёт и пришлите его."
                : "Claude Code зависает ещё до вывода версии. Скопируйте отчёт и пришлите его.";
        } else {
            // 2. Which runtime feature stalls, if any.
            ClaudeRuntime.RunOptions probeOpts = new ClaudeRuntime.RunOptions();
            probeOpts.env.putAll(claudeRuntime.probeEnv());
            JSONObject p = runProbe("проверка рантайма Bun", probeOpts, stages, report);
            boolean trace = p.optBoolean("preload");

            // 3. Full start-up (the path sign-in and replies take), from the
            // plain set-up to the most conservative one.
            if (runFullStart("полный запуск", new ClaudeRuntime.RunOptions(), trace, stages, report)) {
                claudeRuntime.setSafeMode(false);
                ok = true;
                summary = p.optBoolean("ok")
                    ? "Claude Code запускается."
                    : "Claude Code запускается, но проверка рантайма нашла ошибки — подробности в отчёте.";
            } else if (runFullStart("полный запуск (безопасный режим Bun)", safeOptions(null), trace, stages, report)) {
                claudeRuntime.setSafeMode(true);
                ok = true;
                summary = "Claude Code запускается только в безопасном режиме Bun — он включён для входа и ответов.";
            } else if (runFullStart("полный запуск (чистый профиль)", safeOptions(claudeRuntime.freshHome()), trace, stages, report)) {
                // Old Claude Code data was in the way: start the profile over
                // (credentials are carried over) and see if the plain mode works now.
                claudeRuntime.resetHome();
                ok = true;
                if (runFullStart("полный запуск (новый профиль, обычный режим)", new ClaudeRuntime.RunOptions(), trace, stages, report)) {
                    claudeRuntime.setSafeMode(false);
                    summary = "Мешали старые данные Claude Code — профиль создан заново (вход, если был, сохранён).";
                } else {
                    claudeRuntime.setSafeMode(true);
                    summary = "Мешали старые данные Claude Code — профиль создан заново (вход, если был, сохранён); включён безопасный режим Bun.";
                }
            } else {
                JSONObject last = stages.optJSONObject(stages.length() - 1);
                summary = last != null && last.optBoolean("finished")
                    ? "Claude Code при запуске завершается с ошибкой (" + last.optString("exit")
                        + ") во всех режимах. Скопируйте отчёт и пришлите его."
                    : "Claude Code зависает при запуске во всех режимах. Скопируйте отчёт и пришлите его: в нём видно, на чём именно.";
            }
            claudeRuntime.discardFreshHome();
        }
        report.insert(headerEnd, "Итог: " + summary + "\n");

        JSONObject res = new JSONObject();
        res.put("ok", ok);
        res.put("summary", summary);
        res.put("safeMode", claudeRuntime.isSafeMode());
        res.put("stages", stages);
        res.put("report", report.toString().trim());
        return res;
    }

    private static ClaudeRuntime.RunOptions safeOptions(File home) {
        ClaudeRuntime.RunOptions o = new ClaudeRuntime.RunOptions();
        o.safe = true;
        o.home = home;
        return o;
    }

    /**
     * `claude --version` with the probe preloaded: the probe runs its checks and
     * exits before Claude Code does. ok = it finished with no failed check.
     */
    private JSONObject runProbe(String name, ClaudeRuntime.RunOptions opts, JSONArray stages, StringBuilder report) throws Exception {
        claudeSelftestProgress = name;
        List<String> cmd = new ArrayList<>();
        cmd.add("--version");
        opts.preloads.add(ClaudeRuntime.PRELOAD_PROBE);
        JSONObject s = runStage(name, claudeRuntime.newClaudeProcess(cmd, opts), 45000L, 60000L, null, true);
        String out = s.optString("output");
        boolean preload = out.contains("[probe");
        s.put("preload", preload);
        s.put("ok", preload && out.contains("done · всё в порядке"));
        if (!preload && s.optBoolean("finished")) {
            s.put("exit", s.optString("exit") + " · предзагрузка (BUN_OPTIONS) не сработала");
        }
        stages.put(s);
        appendStage(report, s);
        return s;
    }

    /**
     * A full CLI start: `claude auth status` with the debug log on stderr and,
     * when preloads work, the start-up trace (heartbeat + child processes).
     */
    private boolean runFullStart(String name, ClaudeRuntime.RunOptions opts, boolean trace,
                                 JSONArray stages, StringBuilder report) throws Exception {
        claudeSelftestProgress = name;
        // Global options go before the subcommand: the CLI parses positionally.
        List<String> cmd = new ArrayList<>();
        cmd.add("--debug-to-stderr");
        cmd.add("auth");
        cmd.add("status");
        cmd.add("--json");
        if (trace) opts.preloads.add(ClaudeRuntime.PRELOAD_TRACE);
        // Waits longer while Claude Code keeps logging: a slow start is not a hang.
        JSONObject s = runStage(name, claudeRuntime.newClaudeProcess(cmd, opts), 40000L, 150000L, null, true);
        if (trace && s.optBoolean("finished") && s.optString("output").contains("--preload")) {
            // The preload flag reached Claude Code's own arguments: run it plain.
            opts.preloads.remove(ClaudeRuntime.PRELOAD_TRACE);
            s = runStage(name + " (без трассировки)", claudeRuntime.newClaudeProcess(cmd, opts), 40000L, 150000L, null, true);
        }
        // `auth status` exits 1 when signed out; that still proves start-up works.
        String out = s.optString("output");
        if (!s.optBoolean("ok") && s.optInt("exitCode", -1) == 1 && out.contains("loggedIn")) {
            s.put("ok", true);
        }
        stages.put(s);
        appendStage(report, s);
        return s.optBoolean("ok");
    }

    /** The current sign-in has stored credentials (new ones, when signing in again). */
    private boolean newCredentialsStored() {
        return claudeRuntime.isAuthenticated() && claudeRuntime.credentialsStamp() != claudeLoginBaseStamp;
    }

    /** Claude Code runs still in use: the pending sign-in and replies being generated. */
    private List<Process> liveSandboxRuns() {
        List<Process> keep = new ArrayList<>();
        keep.add(pendingClaudeAuthProcess);
        for (GenerationProgress g : activeGenerations.values()) keep.add(g.activeProcess);
        return keep;
    }

    private boolean isDebuggableBuild() {
        return (context.getApplicationInfo().flags & android.content.pm.ApplicationInfo.FLAG_DEBUGGABLE) != 0;
    }

    /**
     * Test builds only (build-apk.ps1 -Debuggable, reached over adb + WebView
     * remote debugging): runs a command line inside the app process's own
     * sandbox (SELinux domain, seccomp filter) with Claude Code's environment
     * plus {@code env}. Paths may use "$RT" for the runtime directory.
     */
    private JSONObject handleDevExec(JSONObject body) throws Exception {
        JSONArray argv = body.optJSONArray("argv");
        if (argv == null || argv.length() == 0) return errorJson(400, "argv required");
        String rt = claudeRuntime.getRuntimeDir().getAbsolutePath();
        List<String> cmd = new ArrayList<>();
        for (int i = 0; i < argv.length(); i++) cmd.add(argv.getString(i).replace("$RT", rt));
        ProcessBuilder pb = claudeRuntime.newHostProcess(cmd);
        JSONObject env = body.optJSONObject("env");
        if (env != null) {
            java.util.Iterator<String> keys = env.keys();
            while (keys.hasNext()) {
                String k = keys.next();
                if (env.isNull(k)) pb.environment().remove(k);
                else pb.environment().put(k, env.getString(k).replace("$RT", rt));
            }
        }
        long timeout = body.optLong("timeoutMs", 30000L);
        return runStage("dev exec", pb, timeout, timeout, null, body.optBoolean("snapshot", true));
    }

    /** What every process this app started is doing right now (for hang reports). */
    private String sandboxSnapshot() {
        try {
            return ProcSnapshot.ofDescendants(android.os.Process.myPid(), claudeRuntime.getRuntimeDir().getAbsolutePath());
        } catch (Exception e) {
            return "(снимок процессов недоступен: " + e.getMessage() + ")";
        }
    }

    private void appendStage(StringBuilder report, JSONObject s) {
        report.append("\n[").append(s.optBoolean("ok") ? "OK" : "FAIL").append("] ").append(s.optString("name"))
            .append(" · ").append(s.optString("exit")).append(" · ").append(s.optString("seconds")).append(" c\n");
        String out = s.optString("output").trim();
        if (!out.isEmpty()) report.append(out).append("\n");
        String verbose = s.optString("verbose").trim();
        if (!verbose.isEmpty()) report.append("--- verbose ---\n").append(verbose).append("\n");
        String snapshot = s.optString("snapshot").trim();
        if (!snapshot.isEmpty()) report.append("--- процессы в момент зависания ---\n").append(snapshot).append("\n");
    }

    /** Runs one diagnostic process with a timeout; ok = exit 0 (and expected text, if given). */
    private JSONObject runStage(String name, ProcessBuilder pb, long timeoutMs, String expect) throws Exception {
        return runStage(name, pb, timeoutMs, timeoutMs, expect, false);
    }

    /**
     * Same, but past {@code timeoutMs} it keeps waiting (up to {@code hardMaxMs})
     * while the process still prints something new, so a slow start is not taken
     * for a hang. A hung process is described from /proc before it is stopped.
     * The output keeps its beginning and its latest part.
     */
    private JSONObject runStage(String name, ProcessBuilder pb, long timeoutMs, long hardMaxMs, String expect,
                                boolean snapshotOnHang) throws Exception {
        JSONObject r = new JSONObject();
        r.put("name", name);
        long started = System.currentTimeMillis();
        pb.redirectErrorStream(true);
        Process proc;
        try {
            proc = pb.start();
        } catch (Exception e) {
            r.put("ok", false);
            r.put("finished", false);
            r.put("exitCode", -2);
            r.put("exit", "не запустился");
            r.put("seconds", "0.0");
            r.put("output", "Не удалось запустить: " + e.getMessage());
            return r;
        }
        try { proc.getOutputStream().close(); } catch (Exception ignored) {}
        final StageOutput out = new StageOutput();
        final Process p = proc;
        Thread t = new Thread(new Runnable() {
            @Override
            public void run() {
                try {
                    BufferedReader br = new BufferedReader(new InputStreamReader(p.getInputStream(), StandardCharsets.UTF_8));
                    String l;
                    while ((l = br.readLine()) != null) out.add(stripAnsi(l));
                } catch (Exception ignored) {
                }
            }
        });
        t.setDaemon(true);
        t.start();
        boolean finished = false;
        while (true) {
            if (!isAlive(proc)) { finished = true; break; }
            long now = System.currentTimeMillis();
            long elapsed = now - started;
            if (elapsed >= hardMaxMs) break;
            if (elapsed >= timeoutMs && now - out.lastProgressAt() > 10000L) break;
            try { Thread.sleep(100); } catch (InterruptedException ignored) { break; }
        }
        long seconds = (System.currentTimeMillis() - started) / 1000;
        if (!finished) {
            if (snapshotOnHang) r.put("snapshot", sandboxSnapshot());
            ClaudeRuntime.kill(proc);
        }
        try { t.join(1500); } catch (InterruptedException ignored) {}
        int code = finished ? proc.exitValue() : -1;
        String text = out.text();
        boolean ok = finished && code == 0 && (expect == null || text.contains(expect));
        r.put("ok", ok);
        r.put("finished", finished);
        r.put("exitCode", code);
        r.put("exit", finished ? describeExit(code) : "нет ответа за " + seconds + " с");
        r.put("seconds", String.format(Locale.US, "%.1f", (System.currentTimeMillis() - started) / 1000.0));
        r.put("output", text);
        return r;
    }

    /** Output of a diagnostic run: the first lines and the latest ones. */
    private static final class StageOutput {
        private static final int HEAD_CHARS = 2500;
        private static final int TAIL_CHARS = 7000;
        private final StringBuilder head = new StringBuilder();
        private final java.util.ArrayDeque<String> tail = new java.util.ArrayDeque<>();
        private int tailChars = 0;
        private int skipped = 0;
        private volatile long lastProgressAt = System.currentTimeMillis();

        synchronized void add(String line) {
            // The trace's heartbeat shows the process is alive, not that it moves on.
            if (!line.contains("] heartbeat ")) lastProgressAt = System.currentTimeMillis();
            if (tail.isEmpty() && skipped == 0 && head.length() + line.length() < HEAD_CHARS) {
                head.append(line).append('\n');
                return;
            }
            tail.addLast(line);
            tailChars += line.length() + 1;
            while (tailChars > TAIL_CHARS && tail.size() > 1) {
                tailChars -= tail.removeFirst().length() + 1;
                skipped++;
            }
        }

        long lastProgressAt() {
            return lastProgressAt;
        }

        synchronized String text() {
            StringBuilder sb = new StringBuilder(head);
            if (skipped > 0) sb.append("… (пропущено строк: ").append(skipped).append(") …\n");
            for (String l : tail) sb.append(l).append('\n');
            return sb.toString().trim();
        }
    }

    /** Exit code with the signal spelled out (Java reports 128 + signal for killed processes). */
    static String describeExit(int code) {
        if (code > 128 && code < 160) {
            int sig = code - 128;
            String[] names = {"", "SIGHUP", "SIGINT", "SIGQUIT", "SIGILL", "SIGTRAP", "SIGABRT", "SIGBUS", "SIGFPE",
                "SIGKILL", "SIGUSR1", "SIGSEGV", "SIGUSR2", "SIGPIPE", "SIGALRM", "SIGTERM", "SIGSTKFLT", "SIGCHLD",
                "SIGCONT", "SIGSTOP", "SIGTSTP", "SIGTTIN", "SIGTTOU", "SIGURG", "SIGXCPU", "SIGXFSZ", "SIGVTALRM",
                "SIGPROF", "SIGWINCH", "SIGIO", "SIGPWR", "SIGSYS"};
            String name = sig < names.length ? names[sig] : ("сигнал " + sig);
            String hint = sig == 31 ? " — системный вызов запрещён Android (seccomp)"
                : sig == 11 ? " — сбой памяти" : sig == 4 ? " — недопустимая инструкция" : sig == 9 ? " — процесс убит" : "";
            return "код " + code + " (" + name + hint + ")";
        }
        return "код " + code;
    }

