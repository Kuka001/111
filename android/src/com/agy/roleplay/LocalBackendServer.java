    /**
     * Virtual secure origin for the UI. Assets are served from this host via
     * {@link #serveVirtualAsset(String)} instead of a real file:// URL, which lets
     * the WebView run with file access fully disabled while still loading the
     * bundled or OTA UI. A real https origin also gives the page a secure context.
     */
    static final String VIRTUAL_HOST = "appassets.agy.local";
    private static final String VIRTUAL_ORIGIN = "https://" + VIRTUAL_HOST;

    public String getStartPageUrl() {
        // Cache-bust so a freshly applied OTA bundle is never served from the
        // WebView's in-memory cache under the (unchanged) virtual URL.
        return VIRTUAL_ORIGIN + "/index.html?v=" + System.currentTimeMillis();
    }

    /** True when a complete OTA bundle is active and should take precedence over assets. */
    private boolean isOtaBundleActive() {
        if (!"1".equals(getSetting("ota_active", "0"))) return false;
        File otaIndex = new File(otaWwwDir, "index.html");
        File otaAppJs = new File(otaWwwDir, "app.js");
        return otaIndex.exists() && otaAppJs.exists() && otaIndex.length() > 100;
    }

    private static String guessMimeType(String path) {
        String p = path.toLowerCase(Locale.ROOT);
        if (p.endsWith(".html") || p.endsWith(".htm")) return "text/html";
        if (p.endsWith(".js")) return "application/javascript";
        if (p.endsWith(".css")) return "text/css";
        if (p.endsWith(".json")) return "application/json";
        if (p.endsWith(".svg")) return "image/svg+xml";
        if (p.endsWith(".png")) return "image/png";
        if (p.endsWith(".jpg") || p.endsWith(".jpeg")) return "image/jpeg";
        if (p.endsWith(".webp")) return "image/webp";
        if (p.endsWith(".gif")) return "image/gif";
        if (p.endsWith(".woff2")) return "font/woff2";
        return "application/octet-stream";
    }

    /**
     * Resolves a virtual-origin request path to a stream.
     * Returns null when the path is unknown so the WebView reports a normal 404.
     *
     * Traversal-safe: the resolved canonical path must stay inside the allowed root.
     */
    InputStream serveVirtualAsset(String rawPath) {
        try {
            String path = rawPath == null ? "" : rawPath;
            int q = path.indexOf('?');
            if (q >= 0) path = path.substring(0, q);
            while (path.startsWith("/")) path = path.substring(1);
            if (path.isEmpty()) path = "index.html";
            // Reject encoded traversal attempts outright.
            if (path.contains("..") || path.contains("%2e%2e") || path.contains("%2E%2E")) return null;

            // 1. An active OTA bundle wins for the UI files.
            if (isOtaBundleActive()) {
                File otaFile = new File(otaWwwDir, path);
                File otaRoot = otaWwwDir.getCanonicalFile();
                if (otaFile.getCanonicalPath().startsWith(otaRoot.getPath() + File.separator) && otaFile.isFile()) {
                    return new FileInputStream(otaFile);
                }
            }

            // 2. Otherwise the read-only assets shipped inside the APK.
            return context.getAssets().open("www/" + path);
        } catch (Exception e) {
            return null;
        }
    }

    String virtualMimeType(String rawPath) {
        String path = rawPath == null ? "" : rawPath;
        int q = path.indexOf('?');
        if (q >= 0) path = path.substring(0, q);
        if (path.isEmpty() || path.endsWith("/")) return "text/html";
        return guessMimeType(path);
    }

    @JavascriptInterface
    public void reloadWebView() {
        mainHandler.post(new Runnable() {
            @Override
            public void run() {
                WebView wv = webView;
                if (wv != null) {
                    wv.clearCache(true);
                    wv.loadUrl(getStartPageUrl());
                }
            }
        });
    }

    @JavascriptInterface
    public void openExternalUrl(final String url) {
        if (url == null || url.trim().isEmpty()) return;
        mainHandler.post(new Runnable() {
            @Override
            public void run() {
                try {
                    Intent intent = new Intent(Intent.ACTION_VIEW, Uri.parse(url.trim()));
                    intent.addFlags(Intent.FLAG_ACTIVITY_NEW_TASK);
                    context.startActivity(intent);
                } catch (Exception ignored) {
                }
            }
        });
    }

    @JavascriptInterface
    public void shareExportText(final String filename, final String content) {
        if (content == null) return;
        mainHandler.post(new Runnable() {
            @Override
            public void run() {
                try {
                    Intent sendIntent = new Intent(Intent.ACTION_SEND);
                    sendIntent.setType("text/plain");
                    sendIntent.putExtra(Intent.EXTRA_SUBJECT, filename != null ? filename : "AGY Roleplay Chat Export");
                    sendIntent.putExtra(Intent.EXTRA_TEXT, content);
                    Intent chooser = Intent.createChooser(sendIntent, "Поделиться экспортированным чатом");
                    chooser.addFlags(Intent.FLAG_ACTIVITY_NEW_TASK);
                    context.startActivity(chooser);
                } catch (Exception ignored) {
                }
            }
        });
    }

